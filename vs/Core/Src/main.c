static int parse_message_and_get_state(const char *msg, fatigue_state_t *out)
{
  if (!msg || !out) return 0;

  const char *p = strstr(msg, "\"status_code\"");
  if (!p) p = strstr(msg, "status_code");
  if (!p) return 0;

  p = strchr(p, ':');
  if (!p) return 0;
  p++;

  while (*p && isspace((unsigned char)*p)) p++;

  if (*p != '"' && *p != '\'') return 0;
  p++;

  while (*p && isspace((unsigned char)*p)) p++;

  char b0 = p[0];
  char b1 = p[1];
  if (!((b0=='0' || b0=='1') && (b1=='0' || b1=='1'))) return 0;

  if      (b0=='0' && b1=='0') *out = STATE_OK;
  else if (b0=='0' && b1=='1') *out = STATE_TIRED;
  else if (b0=='1' && b1=='0') *out = STATE_SLEEPY;
  else return 0;

  return 1;
}



static void CommTask(void *argument)
{
  char msg[RX_BUF_LEN];
  uint16_t idx = 0;

  for (;;)
  {
    uint8_t b;

    if (xQueueReceive(xRxByteQueue, &b, portMAX_DELAY) == pdTRUE)
    {
      char c = (char)b;

      if (idx < RX_BUF_LEN - 1) {
        msg[idx++] = c;
        msg[idx] = '\0';
      } else {
        idx = 0;
        msg[0] = '\0';
      }

      if (c == '\n' || c == '}')
      {
        fatigue_state_t s;
        msg[idx] = '\0';

        if (parse_message_and_get_state(msg, &s))
        {
          // LED: queue (buffer)
          if (xStateQueue) {
            xQueueSend(xStateQueue, &s, 0);
          }

          // Audio: notification (mailbox)
          if (xAudioTaskHandle) {
            xTaskNotify(xAudioTaskHandle, (uint32_t)s, eSetValueWithOverwrite);
          }
        }

        idx = 0;
        msg[0] = '\0';
      }
    }
  }
}


static void LedTask(void *argument)
{
  fatigue_state_t s;

  for (;;)
  {
    if (xQueueReceive(xStateQueue, &s, portMAX_DELAY) == pdTRUE)
    {
      HAL_GPIO_WritePin(GPIOD, GPIO_PIN_12 | GPIO_PIN_13 | GPIO_PIN_14, GPIO_PIN_RESET);

      switch (s)
      {
        case STATE_OK: // 00
          HAL_GPIO_WritePin(GPIOD, GPIO_PIN_12, GPIO_PIN_SET); // zelena
          break;

        case STATE_TIRED: // 01
          HAL_GPIO_WritePin(GPIOD, GPIO_PIN_13, GPIO_PIN_SET); // oranzna
          break;

        case STATE_SLEEPY: // 10
          HAL_GPIO_WritePin(GPIOD, GPIO_PIN_14, GPIO_PIN_SET); // rdeca
          break;

        default:
          break;
      }
    }
  }
}


static void AudioTask(void *argument)
{
  uint32_t notifValue = 0;

  for (;;)
  {
    // cakaj na novo stanje (mailbox notification)
    xTaskNotifyWait(0, 0xFFFFFFFF, &notifValue, portMAX_DELAY);
    fatigue_state_t s = (fatigue_state_t)notifValue;

    if (s == STATE_OK)
    {
      HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_RESET);
    }
    else if (s == STATE_TIRED)
    {
      for (int i = 0; i < 2; i++)
      {
        HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_1);
        vTaskDelay(pdMS_TO_TICKS(200));
        HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_1);
        vTaskDelay(pdMS_TO_TICKS(200));
      }
    }
    else if (s == STATE_SLEEPY)
    {
      for (int i = 0; i < 6; i++)
      {
        HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_1);
        vTaskDelay(pdMS_TO_TICKS(80));
      }
      HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_SET);
    }
  }
}


